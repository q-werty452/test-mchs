let counter = 7712;

export function askAi(question: string): AiAnswer {
  const q = question.toLowerCase();
  const hit = canned.find((c) => c.keys.some((k) => q.includes(k)));
  counter += 1;

  if (!hit) {
    return {
      request_id: `AI-${counter}`,
      model: AI_MODEL,
      question,
      answer:
        'В переданном контексте недостаточно данных для обоснованного ответа.\n\n' +
        'Помощник работает только с тем срезом, который backend передал по внутреннему API, и не обращается к рабочей базе напрямую. ' +
        'Уточните запрос или укажите объект (зону, событие, станцию, сооружение).\n\n' +
        'Запрос передан ответственному сотруднику.',
      confidence: 0.19,
      sources: [],
      handoff: true,
      latency_ms: 640,
      at: iso(0),
    };
  }

  return {
    request_id: `AI-${counter}`,
    model: AI_MODEL,
    question,
    answer: hit.a,
    confidence: hit.confidence,
    sources: hit.sources,
    handoff: hit.confidence < 0.6,
    latency_ms: 900 + Math.round(hit.a.length * 1.4),
    at: iso(0),
  };
}
